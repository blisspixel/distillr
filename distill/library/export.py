"""Export markdown findings/synthesis to clean formatted DOCX."""

import re
from datetime import datetime
from pathlib import Path

from docx import Document
from docx.enum.text import WD_ALIGN_PARAGRAPH
from docx.oxml import OxmlElement
from docx.oxml.ns import qn
from docx.shared import Pt, RGBColor

__all__ = [
    "export_report",
    "markdown_to_docx",
]


def markdown_to_docx(
    md_path: Path, docx_path: Path | None = None, title: str | None = None
) -> Path:
    """Convert a markdown file to a well-formatted DOCX."""
    if docx_path is None:
        docx_path = md_path.with_suffix(".docx")

    content = md_path.read_text(encoding="utf-8")

    doc = Document()
    _setup_styles(doc)

    # Title
    doc_title = title or _extract_title(content) or md_path.stem
    title_para = doc.add_paragraph()
    title_para.alignment = WD_ALIGN_PARAGRAPH.CENTER
    run = title_para.add_run(doc_title)
    run.font.size = Pt(22)
    run.font.color.rgb = RGBColor(0x1A, 0x1A, 0x2E)
    run.bold = True
    title_para.space_after = Pt(4)

    # Subtitle line
    subtitle = doc.add_paragraph()
    subtitle.alignment = WD_ALIGN_PARAGRAPH.CENTER
    run = subtitle.add_run("Generated by Distill")
    run.font.size = Pt(10)
    run.font.color.rgb = RGBColor(0x88, 0x88, 0x88)
    run.italic = True
    subtitle.space_after = Pt(18)

    # Parse and add content
    _parse_markdown(doc, content)

    doc.save(str(docx_path))
    return docx_path


def _setup_styles(doc: Document):
    """Configure document styles for clean output."""
    style = doc.styles["Normal"]
    font = style.font
    font.name = "Aptos"
    font.size = Pt(11)
    font.color.rgb = RGBColor(0x33, 0x33, 0x33)

    pf = style.paragraph_format
    pf.space_before = Pt(0)
    pf.space_after = Pt(6)
    pf.line_spacing = 1.15

    # Heading styles
    for level, (size, color) in enumerate(
        [
            (18, RGBColor(0x1A, 0x1A, 0x2E)),  # Heading 1
            (15, RGBColor(0x2C, 0x3E, 0x50)),  # Heading 2
            (13, RGBColor(0x34, 0x49, 0x5E)),  # Heading 3
        ],
        start=1,
    ):
        style_name = f"Heading {level}"
        if style_name in doc.styles:
            h_style = doc.styles[style_name]
            h_style.font.name = "Aptos"
            h_style.font.size = Pt(size)
            h_style.font.color.rgb = color
            h_style.font.bold = True
            h_style.paragraph_format.space_before = Pt(14 if level == 1 else 10)
            h_style.paragraph_format.space_after = Pt(6)

    # Add a style for bullet list items
    if "List Bullet" in doc.styles:
        lb = doc.styles["List Bullet"]
        lb.font.name = "Aptos"
        lb.font.size = Pt(11)


def _extract_title(content: str) -> str | None:
    """Extract first H1 from markdown content."""
    for line in content.split("\n"):
        line = line.strip()
        if line.startswith("# ") and not line.startswith("##"):
            return line[2:].strip()
    return None


def _parse_markdown(doc: Document, content: str):  # noqa: C901 — legacy, will refactor
    """Parse markdown content into DOCX elements."""
    lines = content.split("\n")
    i = 0
    in_code_block = False
    code_buffer = []

    while i < len(lines):
        line = lines[i]

        # Code blocks
        if line.strip().startswith("```"):
            if in_code_block:
                # End code block
                code_text = "\n".join(code_buffer)
                para = doc.add_paragraph()
                run = para.add_run(code_text)
                run.font.name = "Consolas"
                run.font.size = Pt(9)
                run.font.color.rgb = RGBColor(0x44, 0x44, 0x44)
                para.paragraph_format.space_before = Pt(6)
                para.paragraph_format.space_after = Pt(6)
                code_buffer = []
                in_code_block = False
            else:
                in_code_block = True
            i += 1
            continue

        if in_code_block:
            code_buffer.append(line)
            i += 1
            continue

        stripped = line.strip()

        # Skip empty lines
        if not stripped:
            i += 1
            continue

        # Headings
        if stripped.startswith("### "):
            doc.add_heading(stripped[4:].strip(), level=3)
            i += 1
            continue
        if stripped.startswith("## "):
            doc.add_heading(stripped[3:].strip(), level=2)
            i += 1
            continue
        if stripped.startswith("# "):
            doc.add_heading(stripped[2:].strip(), level=1)
            i += 1
            continue

        # Bullet points
        if stripped.startswith("- ") or stripped.startswith("* "):
            bullet_text = stripped[2:].strip()
            para = doc.add_paragraph(style="List Bullet")
            _add_formatted_text(para, bullet_text)
            i += 1
            continue

        # Numbered lists
        match = re.match(r"^\d+\.\s+(.+)", stripped)
        if match:
            para = doc.add_paragraph(style="List Number")
            _add_formatted_text(para, match.group(1))
            i += 1
            continue

        # Horizontal rules
        if stripped in ("---", "***", "___"):
            # Add a thin line / spacing
            para = doc.add_paragraph()
            para.paragraph_format.space_before = Pt(8)
            para.paragraph_format.space_after = Pt(8)
            run = para.add_run("_" * 60)
            run.font.size = Pt(6)
            run.font.color.rgb = RGBColor(0xCC, 0xCC, 0xCC)
            i += 1
            continue

        # Regular paragraph — collect continuation lines
        para_text = stripped
        while i + 1 < len(lines):
            next_line = lines[i + 1].strip()
            if (
                not next_line
                or next_line.startswith("#")
                or next_line.startswith("- ")
                or next_line.startswith("* ")
                or next_line.startswith("```")
                or re.match(r"^\d+\.\s+", next_line)
                or next_line in ("---", "***", "___")
            ):
                break
            para_text += " " + next_line
            i += 1

        para = doc.add_paragraph()
        _add_formatted_text(para, para_text)
        i += 1


def _add_formatted_text(para, text: str):
    """Add text with inline markdown formatting (bold, italic, code, confidence badges)."""
    # Pattern: **bold**, *italic*, `code`, [text](url), [Confirmed], [Reported], etc.
    pattern = re.compile(
        r"(\*\*(.+?)\*\*)"  # bold
        r"|(\*(.+?)\*)"  # italic
        r"|(`(.+?)`)"  # inline code
        r"|(\[(.+?)\]\((.+?)\))"  # link
        r"|(\[(Confirmed|Reported|Estimated|Speculated|Analysis|High|Medium|Low)\])"  # confidence badges
    )

    pos = 0
    for match in pattern.finditer(text):
        # Add text before this match
        if match.start() > pos:
            para.add_run(text[pos : match.start()])

        if match.group(2):  # bold
            run = para.add_run(match.group(2))
            run.bold = True
        elif match.group(4):  # italic
            run = para.add_run(match.group(4))
            run.italic = True
        elif match.group(6):  # code
            run = para.add_run(match.group(6))
            run.font.name = "Consolas"
            run.font.size = Pt(10)
            run.font.color.rgb = RGBColor(0x88, 0x44, 0x00)
        elif match.group(8):  # link
            run = para.add_run(f"{match.group(8)} ({match.group(9)})")
            run.font.color.rgb = RGBColor(0x22, 0x66, 0xBB)
            run.underline = True
        elif match.group(11):  # confidence badge
            badge = match.group(11)
            badge_colors = {
                "Confirmed": RGBColor(0x1B, 0x7F, 0x3B),  # green
                "High": RGBColor(0x1B, 0x7F, 0x3B),
                "Reported": RGBColor(0x0D, 0x6E, 0xBD),  # blue
                "Medium": RGBColor(0x0D, 0x6E, 0xBD),
                "Estimated": RGBColor(0xCA, 0x83, 0x00),  # amber
                "Analysis": RGBColor(0x6D, 0x28, 0xD9),  # purple
                "Speculated": RGBColor(0xDC, 0x26, 0x26),  # red
                "Low": RGBColor(0xDC, 0x26, 0x26),
            }
            run = para.add_run(f"[{badge}]")
            run.bold = True
            run.font.size = Pt(9)
            run.font.color.rgb = badge_colors.get(badge, RGBColor(0x66, 0x66, 0x66))

        pos = match.end()

    # Add remaining text
    if pos < len(text):
        para.add_run(text[pos:])


