def export_report(
    md_path: Path,
    docx_path: Path | None = None,
    title: str | None = None,
) -> Path:
    """Export an accordion report to a professional DOCX with cover page, TOC, headers."""
    if docx_path is None:
        docx_path = md_path.with_suffix(".docx")

    content = md_path.read_text(encoding="utf-8")

    doc = Document()
    _setup_styles(doc)
    _setup_report_styles(doc)

    # ── Cover Page ──
    _add_cover_page(doc, title or _extract_title(content) or md_path.stem, content)

    # ── Page break after cover ──
    doc.add_page_break()

    # ── Table of Contents ──
    _add_toc(doc, content)

    # ── Page break after TOC ──
    doc.add_page_break()

    # ── Content (skip the H1 title and metadata lines) ──
    _parse_markdown(doc, _strip_front_matter(content))

    # ── Page numbers in footer ──
    _add_page_numbers(doc)

    doc.save(str(docx_path))
    return docx_path


def _setup_report_styles(doc: Document):
    """Add report-specific styles beyond the base setup."""
    # Heading 4 for sub-sub-sections
    if "Heading 4" in doc.styles:
        h4 = doc.styles["Heading 4"]
        h4.font.name = "Aptos"
        h4.font.size = Pt(11)
        h4.font.color.rgb = RGBColor(0x44, 0x55, 0x66)
        h4.font.bold = True
        h4.font.italic = True

    # Ensure List Number style matches
    if "List Number" in doc.styles:
        ln = doc.styles["List Number"]
        ln.font.name = "Aptos"
        ln.font.size = Pt(11)


def _add_cover_page(doc: Document, title: str, content: str):
    """Add a professional cover page."""
    # Top spacer
    for _ in range(4):
        doc.add_paragraph()

    # Title
    title_para = doc.add_paragraph()
    title_para.alignment = WD_ALIGN_PARAGRAPH.CENTER
    run = title_para.add_run(title)
    run.font.size = Pt(28)
    run.font.color.rgb = RGBColor(0x1A, 0x1A, 0x2E)
    run.bold = True
    title_para.space_after = Pt(8)

    # Decorative line
    line_para = doc.add_paragraph()
    line_para.alignment = WD_ALIGN_PARAGRAPH.CENTER
    run = line_para.add_run("_" * 40)
    run.font.size = Pt(8)
    run.font.color.rgb = RGBColor(0x22, 0x66, 0xBB)
    line_para.space_after = Pt(16)

    # Extract metadata from content (the italic lines after H1)
    meta_lines = []
    for line in content.split("\n"):
        stripped = line.strip()
        if stripped.startswith("*") and stripped.endswith("*") and not stripped.startswith("**"):
            # Remove outer asterisks
            meta_text = stripped.strip("*").strip()
            meta_lines.append(meta_text)

    for meta in meta_lines[:3]:
        p = doc.add_paragraph()
        p.alignment = WD_ALIGN_PARAGRAPH.CENTER
        run = p.add_run(meta)
        run.font.size = Pt(11)
        run.font.color.rgb = RGBColor(0x55, 0x55, 0x55)
        run.italic = True
        p.space_after = Pt(2)

    # Spacer
    doc.add_paragraph()
    doc.add_paragraph()

    # Date
    date_para = doc.add_paragraph()
    date_para.alignment = WD_ALIGN_PARAGRAPH.CENTER
    run = date_para.add_run(datetime.now().strftime("%B %d, %Y"))
    run.font.size = Pt(12)
    run.font.color.rgb = RGBColor(0x66, 0x66, 0x66)

    # Generator tag
    gen_para = doc.add_paragraph()
    gen_para.alignment = WD_ALIGN_PARAGRAPH.CENTER
    run = gen_para.add_run("Generated by Distill (Accordion Method)")
    run.font.size = Pt(9)
    run.font.color.rgb = RGBColor(0x99, 0x99, 0x99)
    run.italic = True


def _add_toc(doc: Document, content: str):
    """Add a table of contents extracted from markdown H2 headings."""
    doc.add_heading("Table of Contents", level=1)

    # Extract H2 headings from the markdown
    sections = []
    for line in content.split("\n"):
        stripped = line.strip()
        if stripped.startswith("## ") and not stripped.startswith("###"):
            section_title = stripped[3:].strip()
            # Skip the "Table of Contents" section itself
            if section_title.lower() != "table of contents":
                sections.append(section_title)

    for i, section in enumerate(sections, 1):
        para = doc.add_paragraph()
        run = para.add_run(f"{i}.  ")
        run.font.size = Pt(11)
        run.font.color.rgb = RGBColor(0x66, 0x66, 0x66)
        run = para.add_run(section)
        run.font.size = Pt(11)
        run.font.color.rgb = RGBColor(0x2C, 0x3E, 0x50)
        run.bold = True
        para.paragraph_format.space_after = Pt(4)
        para.paragraph_format.space_before = Pt(2)


def _strip_front_matter(content: str) -> str:
    """Strip the H1 title, metadata lines, and TOC section from content."""
    lines = content.split("\n")
    result = []
    skip_toc = False
    skipped_title = False

    for line in lines:
        stripped = line.strip()

        # Skip the first H1
        if not skipped_title and stripped.startswith("# ") and not stripped.startswith("##"):
            skipped_title = True
            continue

        # Skip metadata italic lines right after title
        if (
            skipped_title
            and not result
            and stripped.startswith("*")
            and stripped.endswith("*")
            and not stripped.startswith("**")
        ):
            continue

        # Skip the Table of Contents section
        if stripped == "## Table of Contents":
            skip_toc = True
            continue
        if skip_toc:
            if stripped.startswith("## ") and stripped != "## Table of Contents":
                skip_toc = False
            elif stripped == "---":
                skip_toc = False
                continue
            else:
                continue

        result.append(line)

    return "\n".join(result)


def _add_page_numbers(doc: Document):
    """Add page numbers to the document footer."""
    for section in doc.sections:
        footer = section.footer
        footer.is_linked_to_previous = False
        para = footer.paragraphs[0] if footer.paragraphs else footer.add_paragraph()
        para.alignment = WD_ALIGN_PARAGRAPH.CENTER

        # Add page number field
        run = para.add_run()
        fldChar1 = OxmlElement("w:fldChar")
        fldChar1.set(qn("w:fldCharType"), "begin")
        run._r.append(fldChar1)

        instrText = OxmlElement("w:instrText")
        instrText.set(qn("xml:space"), "preserve")
        instrText.text = " PAGE "
        run._r.append(instrText)

        fldChar2 = OxmlElement("w:fldChar")
        fldChar2.set(qn("w:fldCharType"), "end")
        run._r.append(fldChar2)

        run.font.size = Pt(9)
        run.font.color.rgb = RGBColor(0x99, 0x99, 0x99)
